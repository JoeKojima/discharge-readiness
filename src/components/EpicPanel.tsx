/** A plain-text discharge coordination note drafted from the coordinator's log (for a clinician to sign in Epic). */
export function draftCoordinationNote(p: Patient, c?: Coordination) {
  const lines = [`Discharge coordination note (draft, generated by ClearPath for clinician review)`, ""]
  lines.push(`Diagnosis: ${p.diagnosis}. Hospital day ${p.los}. Planned destination: ${c?.profile.destination ?? p.disposition}.`)
  if (c) {
    lines.push(`Insurance: ${c.profile.coverage}. Family contact: ${c.profile.family.name} (${c.profile.family.relation}), verified by text.`)
    lines.push("")
    lines.push("Outreach status:")
    for (const s of c.streams.filter((x) => x.kind !== "family")) lines.push(`- ${s.label}, ${s.party}: ${s.note}`)
    if (c.admission) lines.push("", `Discharge planned ${when(c.admission.at)} to ${c.admission.party}.`)
    const open = c.gates.filter((g) => !g.resolved)
    if (open.length) lines.push("", `Open items for staff: ${open.map((g) => g.title).join("; ")}.`)
  } else {
    lines.push("", ...p.summary.map((s) => `- ${s}`))
  }
  lines.push("", "Sources: facility, payer, vendor and family communications logged by the discharge coordinator.")
  return lines.join("\n")
}

const problemFor = (p: Patient): [string, string] => {
  const d = p.diagnosis.toLowerCase()
  if (/chf|heart failure|hfref/.test(d)) return ["I50.9", "Heart failure, unspecified"]
  if (/hip fracture/.test(d)) return ["S72.001A", "Fracture of unspecified part of neck of right femur, initial encounter"]
  if (/pyelonephritis/.test(d)) return ["N10", "Acute pyelonephritis"]
  if (/copd/.test(d)) return ["J44.1", "COPD with (acute) exacerbation"]
  if (/pneumonia/.test(d)) return ["J18.9", "Pneumonia, unspecified organism"]
  if (/ketoacidosis|dka/.test(d)) return ["E10.10", "Type 1 diabetes mellitus with ketoacidosis without coma"]
  if (/cellulitis/.test(d)) return ["L03.116", "Cellulitis of left lower limb"]
  return ["Z75.1", "Person awaiting admission to adequate facility elsewhere"]
}

